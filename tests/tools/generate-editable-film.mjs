// Regenerate the source-backed layer registry from the reviewed benchmark archive.
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const require = createRequire(path.join(repo, 'tests/package.json'));
const {transform} = require('sucrase');
const source = execFileSync('unzip', ['-p', path.join(repo, 'tests/fixtures/test-film/project.zip'), 'src/Composition.tsx'], {encoding: 'utf8'});
const compiled = transform(source + '\nexport {scene};', {transforms: ['typescript', 'jsx', 'imports']}).code;
const module = {exports: {}};
new Function('require', 'module', 'exports', compiled)(name => name === 'remotion' ? {} : require(name), module, module.exports);
const keys = new Map();
// Include every element that can appear within the benchmark's 90 seconds, including transitions.
for (const id of [0, 1, 2, 3, 4, 5]) {
  for (let frame = 0; frame <= 2700; frame += 3) {
    for (const node of module.exports.scene(id, frame / 30)) keys.set(node.k, (keys.get(node.k) ?? false) || node.t === 'text');
  }
}
const registry = [...keys].sort(([a], [b]) => a.localeCompare(b)).map(([key, text]) =>
  `    case ${JSON.stringify(key)}: return <EditableLayer data-ms-editable data-ms-label=${JSON.stringify(key)} node={n} layerKey={key} style={{transform: 'none', opacity: 1, color: '#00000000'${text ? ", content: ''" : ''}}} />;`).join('\n');
const target = path.join(repo, 'Examples/MotionShowcase/Film/LayerRegistry.tsx');
fs.writeFileSync(target, `// Generated by tests/tools/generate-editable-film.mjs. Each film object has independent source edits.\nconst editableObject = (n: any, key: string) => {\n  switch (n.k) {\n${registry}\n    default: throw Error('Missing editable film object: ' + n.k);\n  }\n};\n`);
console.log(`Generated ${keys.size} editable film layers`);

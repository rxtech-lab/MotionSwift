// Regenerate source-backed tracks from actual appearances in the reviewed benchmark.
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const require = createRequire(path.join(repo, 'tests/package.json'));
const {transform} = require('sucrase');

export function filmFrames() {
  let source = execFileSync('unzip', ['-p', path.join(repo, 'tests/fixtures/test-film/project.zip'), 'src/Composition.tsx'], {encoding: 'utf8'});
  // Use the editor's draw adapter, including the same visibility threshold as the SVG painter.
  source = source.replace('const draw=(n:any,key:string)=>', 'const drawSVG=(n:any,key:string)=>')
    .replace('const compose=', 'const draw=(n:any,key:string)=>(n.o??1)<=.004?null:({n,key});\nconst compose=');
  source += `\nexport function objects(frame) {
    const s=frame/COMPOSITION_FPS; let ci=0;
    for(let i=0;i<cues.length;i++) if(s>=cues[i].at) ci=i;
    const cur=cues[ci], u=(s-cur.at)/D;
    const A=u<1?(ci>0?scene(cues[ci-1].id,s-cues[ci-1].at):[]):null;
    return compose(A,scene(cur.id,s-cur.at),u).filter(Boolean);
  }`;
  const compiled = transform(source, {transforms: ['typescript', 'jsx', 'imports']}).code;
  const module = {exports: {}};
  new Function('require', 'module', 'exports', compiled)(name => name === 'remotion' ? {} : require(name), module, module.exports);
  return Array.from({length: module.exports.COMPOSITION_DURATION_IN_FRAMES}, (_, frame) => module.exports.objects(frame));
}

export function layerRegistry(frames) {
  const keys = new Map();
  frames.forEach((objects, frame) => {
    for (const {n, key} of objects) {
      if (!keys.has(key)) keys.set(key, {text: false, spans: []});
      const entry = keys.get(key);
      entry.text ||= n.t === 'text';
      const previous = entry.spans.at(-1);
      if (previous?.end === frame) previous.end = frame + 1;
      else entry.spans.push({start: frame, end: frame + 1});
    }
  });
  const registry = [...keys].sort(([a], [b]) => a.localeCompare(b)).map(([key, {text, spans}]) => {
    const clips = spans.map(({start, end}) =>
      `      if (frame < ${end}) return <EditableLayer data-ms-editable data-ms-label=${JSON.stringify(key)} data-ms-timeline={${JSON.stringify({from: start, duration: end - start, keyframes: {}})}} node={n} layerKey={key} style={{transform: 'none', opacity: 1, color: '#00000000'${text ? ", content: ''" : ''}}} />;`).join('\n');
    return `    case ${JSON.stringify(key)}:\n${clips}\n      return null;`;
  }).join('\n');
  return `// Generated by tests/tools/generate-editable-film.mjs. Each appearance has independent source edits.\nconst editableObject = (n: any, key: string, frame: number) => {\n  switch (key) {\n${registry}\n    default: throw Error('Missing editable film object: ' + key);\n  }\n};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = path.join(repo, 'Examples/MotionShowcase/Film/LayerRegistry.tsx');
  fs.writeFileSync(target, layerRegistry(filmFrames()));
  console.log('Generated film tracks from all 2700 frames, including transitions');
}

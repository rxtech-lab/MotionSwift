import assert from 'node:assert/strict';
import test from 'node:test';
import {loadPortable} from './portable.mjs';

const portable = loadPortable();
const src = 'src/Title.tsx:1:21';
const inspect = source => JSON.parse(portable.text(source, src));
const edit = (source, value) => JSON.parse(portable.edit(source, JSON.stringify({op: 'setText', src, key: 'children', value})));

for (const children of ['让《汉密尔顿》唱中文', 'Hello &amp; goodbye', '{"hello"}', '{`hello`}', '\n  Hello\n  world\n', '{""}']) {
  test(`literal text round trips: ${JSON.stringify(children)}`, () => {
    const before = `export const Film = <div style={{opacity: 1}}>${children}</div>;`;
    assert.equal(inspect(before).editable, true);
    const value = '新的文字 <span> & {braces} "quotes" \\ backslash\nSecond line 😀';
    const changed = edit(before, value);
    assert.equal(inspect(changed.source).value, value);
    assert.ok(changed.source.includes('style={{opacity: 1}}'));
    const restored = JSON.parse(portable.edit(changed.source, JSON.stringify(changed.inverse)));
    assert.equal(restored.source, before);
    const empty = edit(changed.source, '');
    assert.equal(inspect(empty.source).editable, true);
    assert.equal(JSON.parse(portable.edit(empty.source, JSON.stringify(empty.inverse))).source, changed.source);
  });
}

test('text inspection decodes entities and normalizes JSX whitespace', () => {
  assert.equal(inspect('export const Film = <div>Hello &amp; goodbye</div>;').value, 'Hello & goodbye');
  assert.equal(inspect('export const Film = <div>\n  Hello\n  world\n</div>;').value, 'Hello world');
});

for (const children of ['{title}', '{frame > 10 ? "a" : "b"}', '<span>Nested</span>', 'Hello {name}', '{/* keep */}Hello']) {
  test(`refuses destructive text replacement: ${children}`, () => {
    const source = `export const Film = <div>${children}</div>;`;
    assert.equal(inspect(source).editable, false);
    assert.ok(inspect(source).reason);
    assert.throws(() => edit(source, 'replacement'), /refused:/);
  });
}

test('stale source stamps refuse text writes', () => {
  assert.throws(() => edit('\nexport const Film = <div>Hello</div>;', 'replacement'), /stale-source:/);
});

for (const style of ["{opacity: 1}", "{opacity: 1, content: ''}", "{content: 'Original title'}"]) {
  test(`film adapter edits its content style and restores exactly: ${style}`, () => {
    const source = `export const Film = <EditableLayer data-ms-editable node={n} style={${style}} />;`;
    assert.equal(inspect(source).editable, true);
    assert.equal(inspect(source).styleContent, true);
    const changed = edit(source, '新标题');
    assert.equal(inspect(changed.source).value, '新标题');
    assert.match(changed.source, /node=\{n\}/);
    assert.equal(JSON.parse(portable.edit(changed.source, JSON.stringify(changed.inverse))).source, source);
    assert.throws(() => edit(source, ''), /refused: Film text cannot be empty/);
  });
}

for (const argument of ["'Make it move.'", '"Make it move."', '`Make it move.`']) {
  test(`lettering image edits only its text argument: ${argument}`, () => {
    const source = `export const Film = <Img src={lettering(${argument}, 88, '#fff4e8', 590, 230)} data-ms-timeline={{from:8,duration:232,keyframes:{left:[{frame:0,value:-480,easing:'linear'}]}}} style={{left:54,top:145,width:590,height:230}} />;`;
    assert.equal(inspect(source).editable, true);
    assert.equal(inspect(source).value, 'Make it move.');
    const value = '让它动起来。 "quotes" & <tag> {braces}\nNew line 😀';
    const changed = edit(source, value);
    assert.equal(inspect(changed.source).value, value);
    assert.ok(changed.source.endsWith(source.slice(source.indexOf(', 88,'))));
    assert.equal(JSON.parse(portable.edit(changed.source, JSON.stringify(changed.inverse))).source, source);
    const empty = edit(changed.source, '');
    assert.equal(inspect(empty.source).value, '');
    assert.equal(JSON.parse(portable.edit(empty.source, JSON.stringify(empty.inverse))).source, changed.source);
  });
}

for (const expression of ['lettering(title, 88)', 'lettering(`Hello ${name}`, 88)']) {
  test(`bound lettering remains protected: ${expression}`, () => {
    const source = `export const Film = <Img src={${expression}} />;`;
    assert.equal(inspect(source).editable, false);
    assert.match(inspect(source).reason, /generated by code/);
    assert.throws(() => edit(source, 'replacement'), /refused:/);
  });
}

test('lettering does not allow overwriting a later src spread or editing ordinary images', () => {
  const spread = "export const Film = <Img src={lettering('Hello', 88)} {...props} />;";
  assert.equal(inspect(spread).editable, false);
  assert.throws(() => edit(spread, 'replacement'), /refused:/);
  const ordinary = "export const Film = <Img src={staticFile('photo.png')} />;";
  assert.equal(inspect(ordinary).editable, false);
  assert.throws(() => edit(ordinary, 'replacement'), /refused:/);
});
